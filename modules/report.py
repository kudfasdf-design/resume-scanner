"""Report module for exporting analysis results to JSON and formatted Markdown."""

import json
from typing import Dict, Any


def generate_json_report(analysis_result: Dict[str, Any]) -> str:
    """Serialize full analysis result to formatted JSON string."""
    return json.dumps(analysis_result, indent=2, ensure_ascii=False)


def generate_markdown_report(result: Dict[str, Any]) -> str:
    """Generate a clean, structured Markdown evaluation report."""
    contact = result.get("contact", {})
    overall_score = result.get("overall_score", 0)
    section_reports = result.get("section_reports", {})
    strengths = result.get("strengths", [])
    weaknesses = result.get("weaknesses", [])
    suggestions = result.get("suggestions", [])
    roles = result.get("roles", [])
    jobs = result.get("jobs", [])
    learning = result.get("learning_priorities", [])

    lines = [
        f"# ATS Resume Screening & Career Pathway Report",
        f"",
        f"**Candidate Name:** {contact.get('name', 'Candidate')}  ",
        f"**Email:** {contact.get('email', 'N/A')}  ",
        f"**Phone:** {contact.get('phone', 'N/A')}  ",
        f"**LinkedIn:** {contact.get('linkedin', 'N/A')}  ",
        f"**GitHub:** {contact.get('github', 'N/A')}  ",
        f"",
        f"---",
        f"",
        f"## 1. Executive Summary & ATS Score",
        f"",
        f"- **Overall ATS Readiness Score:** **{overall_score} / 100**",
        f"- **Grade:** {'A (Strong Match)' if overall_score >= 80 else 'B (Moderate Match)' if overall_score >= 65 else 'C (Needs Work)'}",
        f"",
        f"### Section Score Breakdown",
        f"| Section | Score (0-100) | Findings |",
        f"| :--- | :--- | :--- |",
    ]

    for sec_name, rep in section_reports.items():
        score = rep.get("score", 0)
        finding = rep.get("findings", ["N/A"])[0] if rep.get("findings") else "Evaluated"
        lines.append(f"| {sec_name.capitalize()} | {score} | {finding} |")

    lines.extend([
        f"",
        f"---",
        f"",
        f"## 2. Key Strengths",
    ])
    if strengths:
        for s in strengths:
            lines.append(f"- {s}")
    else:
        lines.append("- No high-confidence strengths detected.")

    lines.extend([
        f"",
        f"## 3. Critical Weaknesses & Areas for Improvement",
    ])
    if weaknesses:
        for w in weaknesses:
            lines.append(f"- {w}")
    else:
        lines.append("- No critical red flags detected.")

    lines.extend([
        f"",
        f"## 4. Prioritized Actionable Recommendations",
    ])
    for s in suggestions:
        lines.append(f"- **[{s.get('priority', 'Medium')}]** ({s.get('section', 'General')}): {s.get('message', '')}")

    lines.extend([
        f"",
        f"---",
        f"",
        f"## 5. Recommended Job Roles",
    ])
    for r in roles:
        lines.append(f"### {r.get('role')} — **{r.get('match_percent')}% Match**")
        lines.append(f"{r.get('description')}")
        matched = ", ".join(r.get("matched_skills", [])) or "None"
        missing_req = ", ".join(r.get("missing_required", [])) or "None"
        missing_opt = ", ".join(r.get("missing_optional", [])) or "None"
        lines.append(f"- **Matched Skills:** {matched}")
        lines.append(f"- **Missing Required Skills:** {missing_req}")
        lines.append(f"- **Missing Optional Skills:** {missing_opt}")
        lines.append("")

    if learning:
        lines.extend([
            f"### High-Leverage Skills to Learn First",
        ])
        for idx, item in enumerate(learning, 1):
            lines.append(f"{idx}. **{item.get('skill')}** (Demanded across multiple top target roles)")
        lines.append("")

    lines.extend([
        f"---",
        f"",
        f"## 6. Curated Job Openings",
    ])
    for j in jobs[:6]:
        lines.append(f"- **{j.get('title')}** at {j.get('company')} ({j.get('location')}) — **{j.get('match_percent')}% Fit**")
        lines.append(f"  - Matched: {', '.join(j.get('matched_skills', [])) or 'None'}")
        if j.get("skill_gap"):
            lines.append(f"  - Missing Skills: {', '.join(j.get('skill_gap', []))}")
        lines.append(f"  - [Job Link]({j.get('url', '#')})")

    lines.extend([
        f"",
        f"---",
        f"*Report generated by ResumeAI • Rule-Based & NLP ATS Screening Engine*",
    ])

    return "\n".join(lines)

